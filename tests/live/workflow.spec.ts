import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { resolve } from 'node:path'

async function signIn(page: Page, role: string) {
  await page.goto('/login')
  await page.getByLabel('Workspace role').selectOption(role === 'otherpatient' ? 'patient' : role)
  await page.getByLabel('Email address').fill(`${role}@demo.test`)
  await page.getByLabel('Password', { exact: true }).fill(process.env.KNEURA_LIVE_PASSWORD!)
  await page.getByRole('button', { name: 'Enter your workspace' }).click()
  await expect(page).toHaveURL(new RegExp(`/${role === 'otherpatient' ? 'patient' : role}/overview`))
}

test('real DICOM → checkpoint → decisions → report → final role distribution', async ({ page }) => {
  // No route interception: HTTP, sessions, SQLite, inference and PNGs are real.
  await signIn(page, 'radiologist')
  await page.getByRole('button', { name: 'New case', exact: true }).click()
  await page.getByLabel('Patient name', { exact: true }).fill('Verification patient')
  await page.getByLabel('Age', { exact: true }).fill('42')
  await page.getByLabel('Gender').selectOption('Female')
  await page.locator('input[type=file]').setInputFiles(resolve(process.env.KNEURA_LIVE_DATA!, 'demo.zip'))
  await page.getByRole('button', { name: 'Upload study', exact: true }).click()
  await expect(page).toHaveURL(/\/radiologist\/cases\/KN-/)
  const caseId = new URL(page.url()).pathname.split('/')[3]
  const route = `/api/cases/${caseId}`
  const created = await (await page.request.get(route)).json()
  expect(created.study.patientName).toBe('Verification patient')
  expect(created.patient).toMatchObject({name:'Verification patient', age:42, gender:'Female'})
  await page.reload()
  await expect(page.locator('.case-heading .patient-identity')).toContainText('Verification patient')
  await expect(page.locator('.case-heading .patient-identity')).toContainText('42 years / Female')
  await page.request.post('/api/auth/logout')
  await signIn(page, 'orthopedist')
  await expect(page.getByRole('button', { name: caseId, exact: true })).toHaveCount(0)
  expect((await page.request.get(route)).status()).toBe(404)
  expect((await page.request.post(route + '/release-to-patient')).status()).toBe(409)
  await page.request.post('/api/auth/logout')
  await signIn(page, 'radiologist')
  await page.getByRole('button', { name: caseId, exact: true }).click()
  if (!process.env.KNEURA_LIVE_SAMPLE_ZIP) await expect(page.getByRole('note')).toContainText('Synthetic software verification')
  await page.getByRole('button', { name: 'Start analysis', exact: true }).click()
  await expect(page.locator('.finding-row')).toHaveCount(12, { timeout: 90000 })
  const analyzed = await (await page.request.get(route)).json()
  expect(analyzed.analysis.windowsEvaluated).toBe(process.env.KNEURA_LIVE_SAMPLE_ZIP ? 36 : 2)
  expect(analyzed.findings.map((f: { name: string }) => f.name)).toEqual(['ACL', 'MCL', 'Medial Meniscus', 'Lateral Meniscus', 'Medial OA', 'Lateral OA', 'Patellofemoral OA', 'Effusion', 'Synovitis', "Baker's cyst", 'Contusion', 'Fracture'])
  await page.getByRole('button', { name: 'Next slice', exact: true }).click()
  await page.getByRole('button', { name: 'Open evidence in MRI viewer' }).click()
  await expect(page.locator('.viewer-bottom-meta')).toContainText(`INSTANCE ${analyzed.findings[0].evidence.sliceStart}`)
  await page.getByText('Image settings & evidence details', {exact:true}).click()
  await page.getByLabel('Display window width').fill('800')
  await page.getByLabel('Display window level').fill('500')
  await expect(page.locator('.viewer-canvas img')).toHaveAttribute('src', /width=800.*center=500/)
  await page.getByRole('button', { name: 'Grad-CAM', exact: true }).click()
  await page.getByLabel('Grad-CAM opacity').fill('70')
  await expect(page.locator('.viewer-canvas img')).toHaveAttribute('src', /opacity=0.7/)
  await expect(page.locator('.viewer-canvas img')).toBeVisible()
  await page.screenshot({ path: 'test-results/live-real-inference.png', fullPage: true })
  for (let i = 0; i < 12; i++) {
    await page.locator('.finding-row').nth(i).click()
    await page.getByRole('button', { name: i < 3 ? 'Approve' : 'Reject', exact: true }).click()
    await expect(page.locator('.decision-panel .status')).toHaveText(i < 3 ? 'APPROVED' : 'REJECTED')
  }
  await expect(page.locator('.review-progress')).toContainText('12 / 12')
  await page.getByRole('button', { name: 'Continue to report' }).click()
  const liveLLM = process.env.KNEURA_LIVE_LLM === '1'
  if (liveLLM) {
    await page.getByRole('button', { name: 'Generate draft report', exact: true }).click()
    await expect(page.getByLabel('Report findings')).toBeVisible({timeout: 120000})
  } else {
    await page.getByText('Use a template instead (not LLM generated)', {exact:true}).click()
    await page.getByRole('button', { name: 'Generate template draft' }).click()
    await expect(page.getByLabel('Report findings')).toHaveValue(/ACL:/)
  }
  const draft = await (await page.request.get(route)).json()
  expect(draft.report.approvedFindingIds).toEqual(['finding-0', 'finding-1', 'finding-2'])
  if (liveLLM) {
    expect(draft.report.provider).toContain('Live LLM narrative / Google Gemini /')
    expect(draft.reportJob.status).toBe('COMPLETED')
    expect(draft.report.findings).not.toContain('approved by the reviewing radiologist')
  } else expect(draft.report.provider).toBe('Evidence-bound template')
  await page.getByLabel('Report impression').fill('DEMO ONLY. Synthetic software verification reviewed; no clinical interpretation.')
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.locator('.document-toolbar')).toContainText('UNDER REVIEW')
  await page.locator('.statement-traces button').first().click()
  await expect(page.getByRole('dialog')).toContainText('DEMO radiologist')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'DEMO ONLY. Synthetic software verification reviewed; no clinical interpretation.', exact: true }).click()
  await page.getByText('Attach Evidence', { exact: true }).click()
  await page.getByRole('button', { name: 'Save evidence attachment' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Approve final', exact: true }).click()
  await page.getByRole('button', { name: 'Approve final report', exact: true }).click()
  await expect(page.locator('.document-toolbar')).toContainText('FINAL')
  await page.getByRole('button', { name: 'Audit history' }).click()
  await expect(page.locator('.audit-timeline')).toContainText('Final report approved')
  await page.getByRole('button', { name: 'Verify audit chain' }).click()
  await expect(page.getByText('Hash chain verified', { exact: false })).toBeVisible()
  const final = await (await page.request.get(route)).json()
  expect(final.report.revisions[0].version).toBe(1)
  expect(final.audit.every((event: { caseId: string }) => event.caseId === caseId)).toBe(true)
  await page.request.post('/api/auth/logout')
  await signIn(page, 'patient')
  await expect(page.getByRole('button', { name: caseId, exact: true })).toHaveCount(0)
  expect((await page.request.get(route)).status()).toBe(404)
  await page.request.post('/api/auth/logout')
  await signIn(page, 'orthopedist')
  await page.reload()
  const row = page.getByRole('row').filter({has:page.getByRole('button', {name:caseId,exact:true})})
  await expect(row).toContainText('Verification patient')
  await expect(row).toContainText('42 years / Female')
  await page.getByRole('button', { name: caseId, exact: true }).click()
  await expect(page.locator('.finding-row')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Approve', exact: true })).toHaveCount(0)
  const orthopedic = await (await page.request.get(route)).json()
  expect(orthopedic.findings.every((f: object) => !('probability' in f))).toBe(true)
  expect((await page.request.get(analyzed.findings[0].evidence.gradCamImageUrl)).status()).toBe(200)
  expect((await page.request.get(analyzed.findings[3].evidence.gradCamImageUrl)).status()).toBe(404)
  await page.getByRole('button', { name: 'Report workspace' }).click()
  await expect(page.getByLabel('Report impression')).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: 'Approve for Patient', exact: true }).click()
  await expect(page.getByText('RELEASED TO PATIENT', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('RELEASED TO PATIENT', { exact: true })).toBeVisible()
  expect((await (await page.request.get(route)).json()).releasedToPatient).toBe(true)
  await page.request.post('/api/auth/logout')
  await signIn(page, 'patient')
  await page.getByRole('button', { name: caseId, exact: true }).click()
  await expect(page.locator('.patient-summary article')).toHaveCount(3)
  await expect(page.locator('main')).toContainText('Your radiologist has reviewed and approved')
  await expect(page.locator('main')).not.toContainText('REJECTED')
  expect((await page.request.get(analyzed.findings[0].evidence.mriImageUrl)).status()).toBe(404)
  expect((await page.request.post(route + '/report/finalize')).status()).toBe(403)
  await page.screenshot({ path: 'test-results/live-final-patient.png', fullPage: true })
  await page.reload()
  await expect(page.locator('.patient-summary article')).toHaveCount(3)
  await page.request.post('/api/auth/logout')
  await signIn(page, 'otherpatient')
  await expect(page.getByRole('button', { name: caseId, exact: true })).toHaveCount(0)
  expect((await page.request.get(route)).status()).toBe(404)
  expect((await page.request.get(route + '/export')).status()).toBe(404)
  await page.goto(`/patient/mri/${caseId}`)
  await expect(page.locator('main')).toContainText('Case unavailable')
  await page.request.post('/api/auth/logout')
  await signIn(page, 'radiologist')
  await page.getByRole('button', { name: caseId, exact: true }).click()
  await expect(page.getByText('RELEASED TO PATIENT', { exact: true })).toBeVisible()
  await page.request.post('/api/auth/logout')
  await signIn(page, 'patient')
  await page.getByRole('button', { name: caseId, exact: true }).click()
  await expect(page.locator('.patient-summary article')).toHaveCount(3)
})
