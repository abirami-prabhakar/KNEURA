import { useEffect, useRef, useState } from 'react'
import type { Case } from './types'
import { api } from './api'
import { ErrorState, StatusBadge } from './components'
import { reviewComplete } from './workflow'

export function NarrativePanel({item, canReview, onChange}:{item:Case;canReview:boolean;onChange:(item:Case)=>void}) {
  const [health,setHealth]=useState<{configured:boolean;reachable:boolean;provider:string;model:string;error?:string}|null>(null)
  const [error,setError]=useState(''), [busy,setBusy]=useState(false), [attempt,setAttempt]=useState(0)
  const [indication,setIndication]=useState('')
  const requestId=useRef<string | null>(null)
  useEffect(()=>{let active=true;api.llmHealth().then(h=>{if(active)setHealth(h)}).catch(()=>{if(active)setHealth({configured:false,reachable:false,provider:'',model:'',error:'LLM status unavailable.'})});return()=>{active=false}},[attempt])
  const active=item.reportJob?.status==='QUEUED'||item.reportJob?.status==='PROCESSING'
  useEffect(()=>{
    if(!active)return
    let mounted=true
    const timer=setInterval(()=>{api.case(item.id).then(next=>{if(mounted)onChange(next)}).catch(()=>{if(mounted)setError('Could not refresh the report job. Refresh the case to recover its persisted status.')})},1500)
    return()=>{mounted=false;clearInterval(timer)}
  },[active,item.id,onChange])
  const start=async()=>{
    setBusy(true);setError('')
    requestId.current ||= crypto.randomUUID()
    try {
      await api.generateNarrative(item,{indication},requestId.current)
      requestId.current=null
      onChange(await api.case(item.id))
    } catch(err){setError(err instanceof Error?err.message:'Narrative generation failed.')}finally{setBusy(false)}
  }
  return <section className="evidence-card" aria-label="Live LLM narrative"><div className="eyebrow">APPROVED FINDINGS ONLY</div><h2>Generate report with LLM</h2>
    <p>{!health?'Checking LLM availability…':health.reachable?`${health.provider} / ${health.model}`:'LLM unavailable'}</p>
    {health?.error&&<p className="small-copy">{health.error}</p>}
    <button className="text-button" disabled={busy||active} onClick={()=>{setHealth(null);setAttempt(n=>n+1)}}>Check LLM connection</button>
    <label className="report-label">Optional reviewed indication<textarea aria-label="Permitted clinical indication" rows={2} value={indication} disabled={active||busy} onChange={e=>setIndication(e.target.value)} maxLength={2000}/></label>
    <p className="small-copy">Include only authorized, de-identified context. Do not include rejected findings. The provider receives approved finding names and this context; generated prose still requires radiologist review.</p>
    {item.reportJob&&<div role="status"><StatusBadge status={item.reportJob.status}/><p>Job {item.reportJob.id}</p>{item.reportJob.error&&<p>{item.reportJob.error}</p>}</div>}
    {error&&<ErrorState message={error}/>}
    <button className="button primary" disabled={!canReview||!reviewComplete(item.findings)||!health?.reachable||active||busy} onClick={()=>void start()}>{busy||active?'Generating narrative…':item.reportJob?.status==='FAILED'?'Retry LLM report':'Generate draft report'}</button>
    <p className="clinical-note">The report is generated by the configured LLM from approved findings. If generation fails, no template is substituted. Review and save the draft before final approval.</p>
  </section>
}

export function AuditIntegrity({caseId}:{caseId:string}) {
  const [result,setResult]=useState<{valid:boolean;events:number;legacy_events:number;tampered_events:string[];reason?:string}|null>(null)
  const [busy,setBusy]=useState(false),[error,setError]=useState('')
  const verify=async()=>{setBusy(true);setError('');try{setResult(await api.verifyAudit(caseId))}catch(err){setError(err instanceof Error?err.message:'Verification unavailable')}finally{setBusy(false)}}
  return <section className="evidence-card"><h2>Audit integrity</h2><button className="button" disabled={busy} onClick={()=>void verify()}>{busy?'Verifying…':'Verify audit chain'}</button>
    {result&&<p role="status">{result.valid?'Hash chain verified':'Integrity verification failed'} / {result.events} events / {result.legacy_events} legacy events. {result.tampered_events.join(', ')}</p>}
    {error&&<ErrorState message={error}/>}<p className="small-copy">Tamper-evident, not tamper-proof. Administrators with unrestricted storage access can recompute hashes. Legacy events are anchored at upgrade, not retroactively authenticated.</p></section>
}

export function AttachStatementEvidence({item,statementId,onChange}:{item:Case;statementId:string;onChange:(item:Case)=>void}) {
  const options=item.findings.filter(f=>f.status==='APPROVED'&&f.evidence?.id)
  const [id,setId]=useState(options[0]?.id||''),[busy,setBusy]=useState(false),[error,setError]=useState('')
  const selected=options.find(f=>f.id===id)
  const save=async()=>{if(!selected?.evidence?.id||!item.report?.version)return;setBusy(true);setError('');try{onChange(await api.attachEvidence(item.id,statementId,{findingId:id,evidenceId:selected.evidence.id,version:item.report.version}))}catch(err){setError(err instanceof Error?err.message:'Attachment failed')}finally{setBusy(false)}}
  return <details className="study-details"><summary>Attach Evidence</summary><p>Select an approved finding and confirm its actual MRI evidence. Saving creates a new report revision with your explicit attribution.</p>
    <label>Approved finding<select aria-label="Attach approved finding" value={id} onChange={e=>setId(e.target.value)}>{options.map(f=><option key={f.id} value={f.id}>{f.name}</option>)}</select></label>
    {selected?.evidence&&<p className="small-copy">{selected.evidence.seriesName} / Window {selected.evidence.windowNumber} / Instances {selected.evidence.instanceNumbers?.join(', ') || `${selected.evidence.sliceStart}-${selected.evidence.sliceEnd}`}</p>}
    {error&&<ErrorState message={error}/>}<button className="button primary" disabled={busy||!selected} onClick={()=>void save()}>Save evidence attachment</button></details>
}
